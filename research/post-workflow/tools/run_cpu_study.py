def utc() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def canonical(value: object) -> bytes:
    return (json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode()


def digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def plain(path: Path, *, directory: bool = False) -> Path:
    path = path.absolute()
    if path != Path(os.path.normpath(path)) or any(p.is_symlink() for p in (path, *path.parents)):
        raise ValueError(f"noncanonical or symlink path: {path}")
    if not (path.is_dir() if directory else path.is_file()):
        raise ValueError(f"expected existing {'directory' if directory else 'regular file'}: {path}")
    return path


def load(path: Path) -> dict:
    value = json.loads(plain(path).read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"expected JSON object: {path}")  # noqa: TRY004 - malformed evidence
    return value


def save(path: Path, value: object, *, exclusive: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    data = canonical(value)
    if exclusive:
        with path.open("xb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
    else:
        temporary = path.with_name(path.name + ".tmp")
        with temporary.open("wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)


def relative_ref(root: Path, path: Path) -> dict:
    return {"path": plain(path).relative_to(root).as_posix(), "sha256": digest(path)}


def checked_relative(root: Path, name: str) -> Path:
    value = PurePosixPath(name)
    if not isinstance(name, str) or not name or value.is_absolute() or "\\" in name or any(p in (".", "..") for p in name.split("/")):
        raise ValueError("unsafe retained relative path")
    path = plain(root / name)
    path.relative_to(root)
    return path


def verify_refs(root: Path, refs: list[dict]) -> None:
    for ref in refs:
        if digest(checked_relative(root, ref["path"])) != ref["sha256"]:
            raise ValueError(f"retained byte drift: {ref['path']}")


def git_source(source: Path, args: argparse.Namespace) -> dict:
    environment = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    environment.update(GIT_OPTIONAL_LOCKS="0", GIT_NO_REPLACE_OBJECTS="1")
    def read(*words: str) -> str:
        return subprocess.check_output(["git", *words], cwd=source, text=True, timeout=5,
                                       env=environment).strip()
    commit, tree = read("rev-parse", "HEAD"), read("rev-parse", "HEAD^{tree}")
    if read("status", "--porcelain=v1", "--untracked-files=all"):
        raise ValueError("source checkout must be committed and clean")
    if args.expected_source_commit and commit != args.expected_source_commit:
        raise ValueError("source commit differs from explicit admission")
    if args.expected_source_tree and tree != args.expected_source_tree:
        raise ValueError("source tree differs from explicit admission")
    return {"commit": commit, "tree": tree, "checkout": str(source)}


def set_own_affinity(text: str | None) -> list[int]:
    available = sorted(os.sched_getaffinity(0))
    selected = [int(item) for item in text.split(",")] if text else available[:2]
    if len(selected) != 2 or len(set(selected)) != 2 or not set(selected) <= set(available):
        raise ValueError("exactly two distinct admitted logical CPUs are required")
    os.sched_setaffinity(0, selected)
    return sorted(os.sched_getaffinity(0))


def runtime_modules(source: Path) -> tuple[object, object, dict]:
    finite = importlib.import_module("piq_sdk.finite_experiment")
    qualified = importlib.import_module("qualified_cpu_study")
    actual = plain(Path(finite.__file__))
    if actual != source / "packages/python-sdk/src/piq_sdk/finite_experiment.py":
        raise ValueError("PYTHONPATH resolves finite runner outside the admitted source checkout")
    executable = plain(Path(sys.executable).resolve())
    modules = [actual, plain(Path(qualified.__file__)),
               plain(Path(importlib.import_module("piq_experiment_evidence").__file__)), plain(Path(__file__))]
    pins = {"python_executable": str(executable), "python_sha256": digest(executable),
            "python_invoked_as": sys.executable, "python_version": sys.version, "pythonpath": os.environ.get("PYTHONPATH", ""),
            "xoptions": dict(sys._xoptions), "dont_write_bytecode": sys.dont_write_bytecode,
            "modules": [{"path": str(path), "sha256": digest(path)} for path in modules]}
    return finite, qualified, pins


def verify_external(pins: list[dict]) -> None:
    for ref in pins:
        if digest(plain(Path(ref["path"]))) != ref["sha256"]:
            raise ValueError(f"external source/input drift: {ref['path']}")


def toolchain_input(path: Path, adapter: Path) -> tuple[dict, dict, dict]:
    document = load(path)
    toolchain = document.get("toolchain", document)
    # This source helper reads pinned files; it does not execute a codec workload.
    specification = importlib.util.spec_from_file_location("_admitted_codec_source", adapter)
    module = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(module)
    sealed = json.dumps(toolchain, sort_keys=True, separators=(",", ":"))
    module._toolchain(sealed)
    supplied = document.get("configurations")
    configurations = supplied if supplied is not None else {
        "baseline": {"codec": "pigz-gzip", "toolchain": sealed},
        "candidate": {"codec": "zstd", "toolchain": sealed},
    }
    if not isinstance(configurations, dict) or set(configurations) != {"baseline", "candidate"}:
        raise ValueError("configurations must bind baseline and candidate")
    for role, configuration in configurations.items():
        if not isinstance(configuration, dict) or any(type(v) not in (str, int, bool, type(None)) for v in configuration.values()):
            raise ValueError("native configurations must preserve bounded scalar parameters")
        if json.loads(configuration["toolchain"]) != toolchain:
            raise ValueError("each full native configuration must bind the supplied toolchain")
        if configuration["codec"] != ("pigz-gzip" if role == "baseline" else "zstd"):
            raise ValueError("unexpected baseline/candidate codec")
    return document, toolchain, configurations


def source_files(root: Path) -> list[dict]:
    return [relative_ref(root, path) for path in sorted(root.rglob("*")) if path.is_file()]


