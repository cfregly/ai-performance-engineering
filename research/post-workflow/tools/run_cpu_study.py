def proc_identity(pid: int) -> tuple[int, int] | None:
    try:
        raw = Path(f"/proc/{pid}/stat").read_text()
        fields = raw[raw.rfind(")") + 2:].split()
        return int(fields[1]), int(fields[19])  # parent PID and kernel start ticks
    except (OSError, ValueError, IndexError):
        return None


def stop_owned_tree(process: subprocess.Popen) -> dict:
    """Only this CLI and observed descendants, with PID-reuse checks."""
    observed = {}
    identity = proc_identity(process.pid)
    if identity is not None:
        observed[process.pid] = identity[1]
        try:
            os.kill(process.pid, signal.SIGSTOP)
        except ProcessLookupError:
            pass
    for _ in range(5):
        added = False
        for entry in Path("/proc").iterdir():
            if not entry.name.isdigit():
                continue
            pid = int(entry.name)
            current = proc_identity(pid)
            if current is not None and current[0] in observed and pid not in observed:
                observed[pid] = current[1]
                try:
                    os.kill(pid, signal.SIGSTOP)
                except ProcessLookupError:
                    pass
                added = True
        if not added:
            break
    for pid, started in reversed(list(observed.items())):
        current = proc_identity(pid)
        if current is not None and current[1] == started:
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
    process.wait(timeout=3)
    remaining = [pid for pid, started in observed.items() if (current := proc_identity(pid)) is not None and current[1] == started]
    return {"observed_owned_pids": observed, "remaining_owned_pid_identities": remaining}


def configured_api_url(value: str | None) -> str | None:
    if value is None:
        return None
    parsed = urlsplit(value)
    if (parsed.scheme not in {"http", "https"} or not parsed.netloc or parsed.username
            or parsed.password or parsed.query or parsed.fragment or parsed.path not in {"", "/"}):
        raise ValueError("--api-url requires a plain HTTP(S) API origin without credentials or selectors")
    return value.rstrip("/")


def require_capture_environment(environ: dict[str, str]) -> None:
    exposed = sorted(name for name in ("PIQ_API_TOKEN", "PIQ_DECISION_TOKEN") if environ.get(name))
    if exposed:
        raise ValueError("capture refuses PIQ API credentials: " + ", ".join(exposed))


def retention_action(client: object, run_id: str) -> str:
    try:
        client.get_run(run_id)
    except Exception as exc:
        if getattr(exc, "status", None) == 404:
            return "resume-absent-capture"
        raise RuntimeError(
            "configured PIQ run outcome is unknown; refuse retention write"
        ) from exc
    return "complete-existing-custody"


def capture(args: argparse.Namespace, root: Path, receipt: dict, started: float) -> None:
    deadline = started + OUTER_SECONDS
    source = plain(args.source_checkout, directory=True)
    set_own_affinity(args.cpu_affinity)
    current_source = git_source(source, args)
    finite, qualified, runtime_pin = runtime_modules(source)
    frozen = load(root / "FROZEN.json")
    if frozen["source"] != current_source or frozen["runtime"] != runtime_pin:
        raise ValueError("source HEAD/tree, Python/PYTHONPATH, module or harness drift")
    expected = frozen["parameters"]
    if (expected["corpus_root"] != str(plain(args.corpus_root, directory=True)) or expected["source_checkout"] != str(source)
            or expected["toolchain_json"] != str(plain(args.toolchain_json)) or expected["baseline_review"] != str(plain(args.baseline_review))
            or expected["telemetry_admission"] != (str(plain(args.telemetry_admission)) if args.telemetry_admission else None)
            or expected["study_id"] != args.study_id or expected["execution_owner"] != args.execution_owner
            or expected["configured_api_url"] != configured_api_url(args.api_url)
            or expected["expected_index_sha256"] != args.expected_index_sha256 or expected["expected_corpus_sha256"] != args.expected_corpus_sha256
            or expected["cpu_affinity"] != sorted(os.sched_getaffinity(0))):
        raise ValueError("capture arguments differ from frozen preparation")
    verify_refs(root, frozen["files"])
    verify_external(frozen["external_files"])
    toolchain_input(args.toolchain_json, source / "examples/finite-experiments/artifact_codec_adapter.py")
    prepared = root / "prepared"
    design = load(prepared / "design.json")
    registration = load(prepared / "registration.json")
    design_hash = digest(prepared / "design.json")
    if qualified.validate_cpu_design(design) or registration["design_sha256"] != design_hash:
        raise ValueError("frozen CPU protocol/registration is invalid")
    execution = root / "execution"
    execution.mkdir(mode=0o700, exist_ok=False)  # A second capture never repeats attempts.
    save(execution / "EXECUTION-START.json", {"started_at": utc(), "frozen_sha256": digest(root / "FROZEN.json"), "pid": os.getpid()}, exclusive=True)
    receipt.update(stage="capture-preflight", source=current_source, study_design_sha256=design_hash,
                   environment="native-capture-no-network", configured_app_touched=False,
                   gpu_execution="NOT_RUN_NO_ALLOCATION", groups=[], retained=False,
                   retention_state="UNRETAINED")
    selected_api_url = configured_api_url(args.api_url)
    if selected_api_url is None:
        raise ValueError("capture-first workflow requires --api-url for later retention")
    require_capture_environment(os.environ)
    receipt.update(api_url=selected_api_url, api_mode="deferred-retention",
                   live_network_boundary="none-during-capture",
                   capture_api="piq_sdk.capture_manifest")

    def remaining() -> float:
        return deadline - time.monotonic()
    captured_attempts = 0
    try:
        for group in design["groups"]:
            if remaining() < 45:
                raise TimeoutError("insufficient fixed budget to admit another two-attempt group and clean up")
            verify_refs(root, frozen["files"])
            verify_external(frozen["external_files"])
            if git_source(source, args) != frozen["source"] or runtime_modules(source)[2] != frozen["runtime"]:
                raise ValueError("source or admitted runtime changed during the fixed study")
            manifest_path = prepared / "groups" / group["id"] / "plan/manifest.json"
            manifest = load(manifest_path)
            finite.validate_executable_manifest(manifest, manifest_path.parent)
            if digest(manifest_path.parent / "evidence/design.json") != registration["group_design_sha256s"][group["id"]]:
                raise ValueError("registered native group design drift")
            group_result = {"id": group["id"], "state": "PARTIAL", "planned_run_id": manifest["runId"], "started_at": utc()}
            receipt["groups"].append(group_result)
            capture_root = execution / group["id"] / "capture"
            capture_root.parent.mkdir()
            receipt["stage"] = group["id"] + "-capture"
            result = finite.capture_manifest(manifest_path, capture_root)
            group_result.update(native_receipt=result, capture_output=str(capture_root),
                                run_id=result.get("runId") or manifest["runId"], completed_at=utc())
            if (result.get("state") != "CAPTURED" or result.get("runId") != manifest["runId"]
                    or not result.get("submissionSha256") or result.get("retained") is not False
                    or result.get("retentionState") != "UNRETAINED"):
                raise RuntimeError(
                    "native group capture failed; preserve captured evidence, leave retention unstarted, and never retry attempts"
                )
            captured_submission = load(capture_root / "submission.json")
            captured_plan = captured_submission["run"]["finiteExperiment"]
            group_result["attempt_states"] = [item["state"] for item in captured_plan["attempts"]]
            group_result["correctness_accepted"] = captured_plan.get("correctnessReport", {}).get("accepted")
            if (not all(state == "completed" for state in group_result["attempt_states"])
                    or group_result["correctness_accepted"] is not True):
                raise RuntimeError(
                    "native group was captured but failed execution or correctness; preserve it and leave later groups unstarted"
                )
            group_result["state"] = "CAPTURED"
            captured_attempts += len(manifest["finiteExperiment"]["attempts"])
            save(capture_root.parent / "GROUP-HANDBACK.json", group_result, exclusive=True)
            save(root / "PRODUCER-HANDBACK.json", receipt)
        if git_source(source, args) != frozen["source"] or runtime_modules(source)[2] != frozen["runtime"]:
            raise ValueError("source or admitted runtime drifted before final study closure")
        receipt.update(state="COMPLETE", stage="native-study-captured-unretained",
                       scientific_disposition="NOT_EVALUATED_UNTIL_RETENTION",
                       scientific_review="NOT_STARTED", native_attempt_count=captured_attempts,
                       capture_count=len(receipt["groups"]), qualified_package_ready=False)
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        receipt["api_cleanup"] = "not-started-and-not-contacted-by-capture"
        receipt["unstarted_groups"] = [group["id"] for group in design["groups"] if group["id"] not in {result["id"] for result in receipt["groups"]}]
        if receipt["groups"] and receipt["groups"][-1]["state"] != "CAPTURED":
            group_result = receipt["groups"][-1]
            save(execution / group_result["id"] / "GROUP-HANDBACK.json", group_result)
        receipt["remaining_budget_seconds"] = max(0, round(remaining(), 6))


def retain(args: argparse.Namespace, root: Path, receipt: dict, started: float) -> None:
    deadline = started + OUTER_SECONDS
    source = plain(args.source_checkout, directory=True)
    set_own_affinity(args.cpu_affinity)
    current_source = git_source(source, args)
    finite, qualified, runtime_pin = runtime_modules(source)
    frozen = load(root / "FROZEN.json")
    if frozen["source"] != current_source or frozen["runtime"] != runtime_pin:
        raise ValueError("source HEAD/tree, Python/PYTHONPATH, module or harness drift")
    expected = frozen["parameters"]
    if (expected["corpus_root"] != str(plain(args.corpus_root, directory=True)) or expected["source_checkout"] != str(source)
            or expected["toolchain_json"] != str(plain(args.toolchain_json)) or expected["baseline_review"] != str(plain(args.baseline_review))
            or expected["telemetry_admission"] != (str(plain(args.telemetry_admission)) if args.telemetry_admission else None)
            or expected["study_id"] != args.study_id or expected["execution_owner"] != args.execution_owner
            or expected["configured_api_url"] != configured_api_url(args.api_url)
            or expected["expected_index_sha256"] != args.expected_index_sha256 or expected["expected_corpus_sha256"] != args.expected_corpus_sha256
            or expected["cpu_affinity"] != sorted(os.sched_getaffinity(0))):
        raise ValueError("retain arguments differ from frozen preparation")
    verify_refs(root, frozen["files"])
    verify_external(frozen["external_files"])
    toolchain_input(args.toolchain_json, source / "examples/finite-experiments/artifact_codec_adapter.py")
    prepared = root / "prepared"
    execution = plain(root / "execution", directory=True)
    producer = load(root / "PRODUCER-HANDBACK.json")
    if (producer.get("state") != "COMPLETE" or producer.get("stage") != "native-study-captured-unretained"
            or producer.get("retention_state") != "UNRETAINED"):
        raise ValueError("retain requires one complete unretained capture handback")
    design = load(prepared / "design.json")
    registration = load(prepared / "registration.json")
    design_hash = digest(prepared / "design.json")
    if qualified.validate_cpu_design(design) or registration["design_sha256"] != design_hash:
        raise ValueError("frozen CPU protocol/registration is invalid")
    selected_api_url = configured_api_url(args.api_url)
    producer_token = os.environ.get("PIQ_API_TOKEN")
    decision_token = os.environ.get("PIQ_DECISION_TOKEN")
    if selected_api_url is None or not producer_token or not decision_token:
        raise ValueError("retain requires --api-url and Root-provided PIQ_API_TOKEN and PIQ_DECISION_TOKEN")
    from piq_sdk.client import PIQClient
    client = PIQClient(selected_api_url, producer_token, decision_token=decision_token,
                       timeout=RETENTION_IO_TIMEOUT_SECONDS, max_retries=0)
    save(execution / "RETENTION-START.json",
         {"started_at": utc(), "frozen_sha256": digest(root / "FROZEN.json"), "pid": os.getpid()},
         exclusive=True)
    receipt.update(stage="retention-preflight", source=current_source,
                   study_design_sha256=design_hash, environment="post-cleanup-configured-api-retention",
                   api_url=selected_api_url, configured_app_touched=False, native_execution=False,
                   child_executions=0, groups=[], retention_state="IN_PROGRESS")
    all_samples, census, envelope_refs = [], [], []

    def remaining() -> float:
        return deadline - time.monotonic()

    try:
        for group in design["groups"]:
            if remaining() < 10:
                raise TimeoutError("insufficient fixed budget to admit another retention reconciliation")
            verify_refs(root, frozen["files"])
            verify_external(frozen["external_files"])
            if git_source(source, args) != frozen["source"] or runtime_modules(source)[2] != frozen["runtime"]:
                raise ValueError("source or admitted runtime changed during retention")
            manifest_path = prepared / "groups" / group["id"] / "plan/manifest.json"
            manifest = load(manifest_path)
            finite.validate_executable_manifest(manifest, manifest_path.parent)
            if digest(manifest_path.parent / "evidence/design.json") != registration["group_design_sha256s"][group["id"]]:
                raise ValueError("registered native group design drift")
            capture_root = plain(execution / group["id"] / "capture", directory=True)
            capture_receipt = load(capture_root / "handback.json")
            if (capture_receipt.get("state") != "CAPTURED" or capture_receipt.get("runId") != manifest["runId"]
                    or capture_receipt.get("retentionState") != "UNRETAINED"):
                raise ValueError("capture handback is not an exact unretained group")
            action = retention_action(client, manifest["runId"])
            group_result = {"id": group["id"], "state": "PARTIAL", "run_id": manifest["runId"],
                            "started_at": utc(), "retention_action": action, "native_execution": False}
            receipt["groups"].append(group_result)
            retention_root = execution / group["id"] / "retention"
            receipt["configured_app_touched"] = None
            if action == "resume-absent-capture":
                result = finite.resume_capture(capture_root, retention_root, client)
            else:
                result = finite.complete_capture_custody(capture_root, retention_root, client)
            group_result.update(retention_receipt=result, retention_output=str(retention_root), completed_at=utc())
            if (result.get("state") != "COMPLETE" or result.get("retained") is not True
                    or result.get("runId") != manifest["runId"]):
                raise RuntimeError("group retention did not complete; preserve its receipt and stop without another write")
            receipt["configured_app_touched"] = True
            bundle_errors = qualified.validate_bundle(retention_root)
            if bundle_errors:
                raise ValueError("retained native group evidence invalid: " + "; ".join(bundle_errors))
            envelope = load(retention_root / "envelope.json")
            envelope_ref = relative_ref(root, retention_root / "envelope.json")
            envelope_refs.append(envelope_ref)
            readback = load(retention_root / "run-readback.json")
            group_samples = []
            for attempt in envelope["attempts"]:
                raw_path = checked_relative(retention_root, attempt["raw_result"]["path"])
                raw = load(raw_path)
                row = {"group_id": group["id"], "role": attempt["role"], "run_id": attempt["run_id"],
                       "attempt_id": attempt["id"], "envelope": envelope_ref,
                       "raw_result": relative_ref(root, raw_path)}
                census.append(row)
                if attempt["status"] != "succeeded" or attempt["accepted"] is not True:
                    group_result.setdefault("failed_attempts", []).append(attempt)
                    continue
                observation_name = raw["adapter_result"]["native_evidence"]["observations"]["artifactName"]
                observation_path = checked_relative(
                    retention_root,
                    (PurePosixPath(raw["native_attempt"]["output"]["artifactName"]).parent / observation_name).as_posix(),
                )
                observations = load(observation_path)
                group_samples.append(
                    qualified.normalize_cpu_sample(
                        design, group, envelope, raw, observations, design_sha256=design_hash
                    )
                )
            all_samples.extend(group_samples)
            group_result.update(event_count=readback.get("eventCount"),
                                artifact_count=readback.get("artifactCount"), attempts=envelope["attempts"])
            save(execution / "raw-census.json",
                 {"study_id": args.study_id, "design_sha256": design_hash, "attempts": census})
            save(execution / "observed-samples.json",
                 {"study_id": args.study_id, "design_sha256": design_hash, "samples": all_samples})
            if len(group_samples) != 2 or envelope["correctness"]["accepted"] is not True:
                raise RuntimeError("retained group failed; preserve all evidence and leave remaining groups unstarted")
            group_result["state"] = "COMPLETE"
            save(retention_root.parent / "RETENTION-HANDBACK.json", group_result, exclusive=True)
            save(root / "RETENTION-HANDBACK.json", receipt)
        if git_source(source, args) != frozen["source"] or runtime_modules(source)[2] != frozen["runtime"]:
            raise ValueError("source or admitted runtime drifted before final study closure")
        report = qualified.evaluate_cpu_study(design, all_samples, design_sha256=design_hash)
        save(execution / "qualification-report.json", report, exclusive=True)
        save(execution / "correctness.json",
             {"study_id": args.study_id, "design_sha256": design_hash, "accepted": True,
              "attempts": [{"run_id": sample["run_id"], "attempt_id": sample["attempt_id"],
                            "parts": sample["parts"]} for sample in all_samples]},
             exclusive=True)
        receipt.update(state="COMPLETE", stage="retained-study-complete",
                       retention_state="RETAINED", scientific_disposition=report["verdict"],
                       scientific_review="REQUIRED_NOT_GENERATED", piq_envelopes=envelope_refs,
                       native_attempt_count=len(census), qualified_package_ready=False)
    finally:
        receipt["unstarted_groups"] = [group["id"] for group in design["groups"]
                                       if group["id"] not in {result["id"] for result in receipt["groups"]}]
        if receipt["groups"] and receipt["groups"][-1]["state"] != "COMPLETE":
            group_result = receipt["groups"][-1]
            save(execution / group_result["id"] / "RETENTION-HANDBACK.json", group_result)
        if census:
            save(execution / "raw-census.json",
                 {"study_id": args.study_id, "design_sha256": design_hash, "attempts": census})
        receipt["remaining_budget_seconds"] = max(0, round(remaining(), 6))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("prepare", "capture", "retain"))
    for name in ("source-checkout", "study-root", "corpus-root", "toolchain-json", "baseline-review"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--telemetry-admission", type=Path)
    parser.add_argument("--api-url", required=True,
                        help="Configured API origin frozen at prepare; contacted only by retain with Root-provided credentials")
    parser.add_argument("--study-id", default="public-artifact-codec-qualified-cpu-v1")
    parser.add_argument("--execution-owner", default="designated execution owner")
    parser.add_argument("--cpu-affinity", help="Two admitted CPU IDs; defaults to first two currently allowed CPUs")
    parser.add_argument("--expected-source-commit")
    parser.add_argument("--expected-source-tree")
    parser.add_argument("--expected-python", type=Path, default=Path("/opt/piq/dev-fast/repo/services/api/.venv/bin/python"))
    parser.add_argument("--expected-index-sha256", default=DEFAULT_INDEX_SHA)
    parser.add_argument("--expected-corpus-sha256", default=DEFAULT_CORPUS_SHA)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    started = time.monotonic()
    root = args.study_root.absolute()
    root.mkdir(parents=False, exist_ok=True, mode=0o700)
    plain(root, directory=True)
    receipt = {"state": "PARTIAL", "command": args.command, "started_at": utc(), "stage": "preflight",
               "outer_budget_seconds": OUTER_SECONDS, "configured_app_touched": False, "gpu_count": 0,
               "qualified_package_ready": False}
    handback = root / ({"prepare": "PREPARE-HANDBACK.json", "capture": "PRODUCER-HANDBACK.json",
                       "retain": "RETENTION-HANDBACK.json"}[args.command])
    lock = root / ".producer-lock"
    acquired = False
    previous_alarm = None
    previous_term = None
    try:
        if args.command == "capture" and (root / "execution").exists():
            handback = root / ("REFUSED-REPEAT-CAPTURE-" + secrets.token_hex(8) + ".json")
            raise ValueError("capture is single-use; preserve the original producer handback and never retry attempts")
        if args.command == "retain" and not (root / "execution").is_dir():
            handback = root / ("REFUSED-RETAIN-WITHOUT-CAPTURE-" + secrets.token_hex(8) + ".json")
            raise ValueError("retain requires an existing complete capture")
        if args.command == "retain" and (root / "execution/RETENTION-START.json").exists():
            handback = root / ("REFUSED-REPEAT-RETENTION-" + secrets.token_hex(8) + ".json")
            raise ValueError("retention is single-use; reconcile its original handback without another run POST")
        try:
            descriptor = os.open(lock, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        except FileExistsError:
            handback = root / ("REFUSED-ACTIVE-OWNER-" + secrets.token_hex(8) + ".json")
            raise ValueError("another owner holds the producer lock; do not steal or overwrite its handback")
        acquired = True
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(canonical({"pid": os.getpid(), "started_at": utc(), "command": args.command}))
            stream.flush()
            os.fsync(stream.fileno())
        def terminated(signum, frame):
            signal.signal(signal.SIGTERM, signal.SIG_IGN)
            raise InterruptedError("producer received SIGTERM; retain partial evidence and clean up")
        previous_term = signal.signal(signal.SIGTERM, terminated)
        if Path(sys.executable).absolute() != args.expected_python.absolute() or not sys.dont_write_bytecode or sys._xoptions.get("pycache_prefix") != "/var/empty/piq-python-cache":
            raise ValueError("invoke with the admitted exact Python path, -B and -X pycache_prefix=/var/empty/piq-python-cache")
        if args.command == "prepare":
            prepare(args, root, receipt)
        elif args.command == "capture":
            def expire(signum, frame):
                raise TimeoutError("fixed 240-second outer window reached its cleanup reserve")
            previous_alarm = signal.signal(signal.SIGALRM, expire)
            signal.setitimer(signal.ITIMER_REAL, max(0.1, OUTER_SECONDS - CLEANUP_RESERVE - (time.monotonic() - started)))
            capture(args, root, receipt, started)
        else:
            def expire(signum, frame):
                raise TimeoutError("fixed retention window reached its cleanup reserve")
            previous_alarm = signal.signal(signal.SIGALRM, expire)
            signal.setitimer(signal.ITIMER_REAL, max(0.1, OUTER_SECONDS - CLEANUP_RESERVE - (time.monotonic() - started)))
            retain(args, root, receipt, started)
    except BaseException as exc:  # noqa: BLE001 - every failure must write a durable handback
        receipt.update(state="PARTIAL", error_type=type(exc).__name__, error=str(exc)[:1000])
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        if previous_alarm is not None:
            signal.signal(signal.SIGALRM, previous_alarm)
        if previous_term is not None:
            signal.signal(signal.SIGTERM, previous_term)
        receipt.update(completed_at=utc(), elapsed_seconds=round(time.monotonic() - started, 6))
        save(handback, receipt)
        if acquired:
            lock.unlink()
        print(json.dumps(receipt, sort_keys=True))
    return 0 if receipt["state"] == "COMPLETE" else 1


if __name__ == "__main__":
    raise SystemExit(main())
