#!/usr/bin/env python3
"""Prepare, capture, then retain one immutable prospective CPU codec study.

No command runs on import. Run under the admitted Python/PYTHONPATH. Required
arguments for both verbs: --source-checkout, --study-root, --corpus-root,
--toolchain-json, --baseline-review. Corpus root contains input-index.json and
its inputs/ references. Toolchain input is either the sealed toolchain object or
{toolchain, configurations:{baseline:<full scalar config>,candidate:<config>}}.
Extra native configuration fields are preserved, not inferred or discarded.
--api-url binds the configured API used only by the later retain command.
Prepare and capture validate and freeze that origin but never contact it.
Capture rejects PIQ credentials in its environment and calls the canonical
capture_manifest API without a client. After native cleanup, retain uses
Root-provided PIQ_API_TOKEN and PIQ_DECISION_TOKEN. A fresh exact 404 may use
resume_capture; an existing exact run uses custody completion without another
run POST; every unknown read outcome stops without a write.

An independent baseline review and --telemetry-admission must bind the exact
prepared design before registration is finalized. If either is pending, prepare
returns PARTIAL with the concrete design hash; repeat prepare after actual
review, reusing the same plans/IDs. There is never an experiment in prepare.
Pass the eventual --telemetry-admission path on the first prepare, even while its
real review is pending; input paths and all native configuration are frozen.
Capture is single-use, never resumes/retries a scientific attempt, has a 240 s
outer budget, and writes PRODUCER-HANDBACK.json even after exceptions. Retain
never launches a child and writes RETENTION-HANDBACK.json.

The telemetry admission is real owner-supplied JSON, not generated by this file:
{kind:'piq.cpu-study-telemetry-admission.v1', status:'APPROVED', reviewer,
 reviewed_at, design_sha256, source_commit, source_tree,
 all_required_telemetry_accounted_for:true, reasoning, requirements:[...] }.
Every requirement has name, status ('configured' or 'not_applicable'), reasoning.
Root must review the actual ALL-telemetry obligations before supplying it.
No baseline/scientific review, host observation or execution claim is invented.
"""
